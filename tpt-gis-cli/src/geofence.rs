//! `geofence-compile`: turns GeoJSON polygons into a Rust module of `const`/`static`
//! data for embedded (`no_std`, zero-allocation) geofence checks.
//!
//! The generated module depends only on `tpt-gis-geom`. It declares a `Geofence`
//! struct and a `GEOFENCES` table: each entry has a name, a bounding box for a cheap
//! reject test, the exterior ring, and any holes, all as `'static` slices. Feed a
//! position to `tpt_gis_geom::predicates::point_in_ring` (after checking the bbox) to
//! test it.

use std::fmt::Write as _;

use serde_json::Value;
use tpt_gis_io::geojson::Feature;
use tpt_gis_io::geometry::{Geometry, Point, Polygon};

/// One compiled polygon, ready to emit.
struct Zone {
    name: String,
    exterior: Vec<Point>,
    holes: Vec<Vec<Point>>,
}

/// Generates the Rust source for the polygon features in `features`.
///
/// Feature names come from a `name` property when present, else `zone_<index>`.
/// Multi-polygons contribute one zone per part (`<name>_<part>`). Points, lines, and
/// features without geometry are skipped.
///
/// # Errors
/// Returns a message if a coordinate is not finite, or if no polygon is found.
pub fn generate(features: &[Feature]) -> Result<String, String> {
    let mut zones = Vec::new();
    for (index, feature) in features.iter().enumerate() {
        let base = feature
            .properties
            .get("name")
            .and_then(Value::as_str)
            .map_or_else(|| format!("zone_{index}"), str::to_string);
        match &feature.geometry {
            Some(Geometry::Polygon(p)) => zones.push(zone_from(&base, p)?),
            Some(Geometry::MultiPolygon(parts)) => {
                for (part, p) in parts.iter().enumerate() {
                    zones.push(zone_from(&format!("{base}_{part}"), p)?);
                }
            }
            _ => {}
        }
    }
    if zones.is_empty() {
        return Err("no Polygon or MultiPolygon features to compile".to_string());
    }
    Ok(render(&zones))
}

fn zone_from(name: &str, polygon: &Polygon) -> Result<Zone, String> {
    let exterior = polygon.exterior().to_vec();
    if exterior.is_empty() {
        return Err(format!("polygon '{name}' has no exterior ring"));
    }
    for p in polygon.rings.iter().flatten() {
        if !p.x.is_finite() || !p.y.is_finite() {
            return Err(format!("polygon '{name}' has a non-finite coordinate"));
        }
    }
    Ok(Zone { name: name.to_string(), exterior, holes: polygon.interiors().to_vec() })
}

/// The identifier stem for a zone: upper-case, non-alphanumerics replaced by `_`.
fn ident(name: &str, index: usize) -> String {
    let mut out: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' })
        .collect();
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out = format!("ZONE_{out}");
    }
    format!("{out}_{index}")
}

fn ring_literal(out: &mut String, ring: &[Point]) {
    out.push_str("&[");
    for p in ring {
        // `{:?}` prints a float that round-trips and is a valid Rust literal.
        let _ = write!(out, "Point::new({:?}, {:?}), ", p.x, p.y);
    }
    out.push(']');
}

fn render(zones: &[Zone]) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `tptgis geofence-compile`. Do not edit by hand.\n");
    out.push_str("//\n");
    out.push_str("// Requires `tpt-gis-geom`. Test a position by checking `bbox` first, then\n");
    out.push_str("// `point_in_ring(p, zone.exterior)` and no hole containing `p`.\n\n");
    out.push_str("use tpt_gis_geom::{Point, Rect};\n\n");
    out.push_str("/// One compiled geofence zone.\n");
    out.push_str("#[derive(Debug, Clone, Copy)]\n");
    out.push_str("pub struct Geofence {\n");
    out.push_str("    /// Zone name (the `name` property, or `zone_<index>`).\n");
    out.push_str("    pub name: &'static str,\n");
    out.push_str("    /// Bounding box of the exterior ring.\n");
    out.push_str("    pub bbox: Rect,\n");
    out.push_str("    /// The exterior ring (closed).\n");
    out.push_str("    pub exterior: &'static [Point],\n");
    out.push_str("    /// Interior rings (holes), if any.\n");
    out.push_str("    pub holes: &'static [&'static [Point]],\n");
    out.push_str("}\n\n");

    let mut entries = Vec::new();
    for (i, zone) in zones.iter().enumerate() {
        let stem = ident(&zone.name, i);
        let _ = write!(out, "const {stem}_EXTERIOR: &[Point] = ");
        ring_literal(&mut out, &zone.exterior);
        out.push_str(";\n");
        let _ = write!(out, "const {stem}_HOLES: &[&[Point]] = &[");
        for hole in &zone.holes {
            ring_literal(&mut out, hole);
            out.push_str(", ");
        }
        out.push_str("];\n");
        entries.push((zone, stem));
    }

    out.push_str("\n/// Every compiled geofence, in input order.\n");
    let _ = writeln!(out, "pub const GEOFENCES: [Geofence; {}] = [", zones.len());
    for (zone, stem) in &entries {
        let (min_x, min_y, max_x, max_y) = bbox_of(&zone.exterior);
        let _ = writeln!(
            out,
            "    Geofence {{ name: {:?}, bbox: Rect::new(Point::new({min_x:?}, {min_y:?}), Point::new({max_x:?}, {max_y:?})), exterior: {stem}_EXTERIOR, holes: {stem}_HOLES }},",
            zone.name,
        );
    }
    out.push_str("];\n");
    out
}

fn bbox_of(ring: &[Point]) -> (f64, f64, f64, f64) {
    ring.iter().fold(
        (f64::INFINITY, f64::INFINITY, f64::NEG_INFINITY, f64::NEG_INFINITY),
        |(a, b, c, d), p| (a.min(p.x), b.min(p.y), c.max(p.x), d.max(p.y)),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Map;

    fn feature(name: Option<&str>, geometry: Geometry) -> Feature {
        let mut properties = Map::new();
        if let Some(n) = name {
            properties.insert("name".into(), Value::String(n.into()));
        }
        Feature { geometry: Some(geometry), properties }
    }

    fn square(x0: f64, y0: f64, x1: f64, y1: f64) -> Vec<Point> {
        vec![
            Point::new(x0, y0),
            Point::new(x1, y0),
            Point::new(x1, y1),
            Point::new(x0, y1),
            Point::new(x0, y0),
        ]
    }

    #[test]
    fn emits_named_zone_with_bbox_and_hole() {
        let poly =
            Polygon { rings: vec![square(0.0, 0.0, 10.0, 10.0), square(4.0, 4.0, 6.0, 6.0)] };
        let src =
            generate(&[feature(Some("restricted airspace"), Geometry::Polygon(poly))]).unwrap();
        assert!(src.contains("pub const GEOFENCES: [Geofence; 1]"), "{src}");
        assert!(src.contains("name: \"restricted airspace\""), "{src}");
        assert!(src.contains("Rect::new(Point::new(0.0, 0.0), Point::new(10.0, 10.0))"), "{src}");
        assert!(src.contains("RESTRICTED_AIRSPACE_0_HOLES"), "{src}");
    }

    #[test]
    fn multipolygon_yields_one_zone_per_part() {
        let parts = vec![
            Polygon::from_exterior(square(0.0, 0.0, 1.0, 1.0)),
            Polygon::from_exterior(square(5.0, 5.0, 6.0, 6.0)),
        ];
        let src = generate(&[feature(Some("b"), Geometry::MultiPolygon(parts))]).unwrap();
        assert!(src.contains("[Geofence; 2]"), "{src}");
        assert!(src.contains("name: \"b_0\"") && src.contains("name: \"b_1\""), "{src}");
    }

    #[test]
    fn non_polygon_features_are_skipped_and_empty_input_is_an_error() {
        let pt = feature(None, Geometry::Point(Point::new(1.0, 2.0)));
        assert!(generate(&[pt]).is_err());
    }

    #[test]
    fn non_finite_coordinates_are_rejected() {
        let poly = Polygon::from_exterior(vec![Point::new(f64::NAN, 0.0)]);
        assert!(generate(&[feature(None, Geometry::Polygon(poly))]).is_err());
    }

    #[test]
    fn identifiers_are_valid_rust() {
        assert_eq!(ident("zone-1", 0), "ZONE_1_0");
        assert_eq!(ident("1st", 2), "ZONE_1ST_2");
        assert_eq!(ident("", 3), "ZONE__3");
    }
}
